using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using SteamApp.Domain.Entities;

namespace SteamApp.Infrastructure.Persistence.Configurations;

internal sealed class AutomaticQueueDefinitionConfiguration : IEntityTypeConfiguration<AutomaticQueueDefinition>
{
    public void Configure(EntityTypeBuilder<AutomaticQueueDefinition> entity)
    {
        entity.ToTable("automatic_queue_definition");
        entity.HasKey(x => x.Id);
        entity.Property(x => x.Id).HasColumnName("id");
        entity.Property(x => x.UserId).HasColumnName("user_id");
        entity.Property(x => x.Name).HasColumnName("name");
        entity.Property(x => x.CreatedAtUtc).HasColumnName("created_at_utc");
        entity.Property(x => x.UpdatedAtUtc).HasColumnName("updated_at_utc");
    }
}
